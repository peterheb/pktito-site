// public/tokens.css from design/tokens.json (the design system's, by npm run
// sync): every token as a custom property, light on :root, dark under the
// system's setting unless the page is set light, and again when it is set
// dark; the fonts as @font-face from public/fonts.
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync("design/tokens.json", "utf8"));
const cv = (v) => (v.startsWith("{") ? `var(--${v.slice(1, -1)})` : v);
const light = [], dark = [];
for (const fam of ["color", "shadow"])
  for (const tok of t[fam].tokens) {
    const v = tok.value;
    const [l, d] = typeof v === "string" ? [v, v] : [v.light, v.dark ?? v.light];
    light.push(`  --${tok.name}: ${cv(l)};`);
    if (d !== l) dark.push(`  --${tok.name}: ${cv(d)};`);
  }
for (const fam of ["spacing", "radius", "layout"])
  for (const tok of t[fam].tokens) light.push(`  --${tok.name}: ${tok.value};`);
for (const [k, v] of Object.entries(t.type.families)) light.push(`  --font-${k}: ${v};`);
const faces = t.type.fonts
  .map((f) => `@font-face { font-family: "${f.family}"; src: url("${f.file}") format("woff2"); font-weight: ${f.weight}; font-style: normal; font-display: swap; }`)
  .join("\n");

writeFileSync(
  "public/tokens.css",
  `/* pktito tokens, generated by scripts/tokens.mjs from design/tokens.json */

${faces}

:root {
  color-scheme: light;
${light.join("\n")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.map((d) => "  " + d).join("\n")}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${dark.join("\n")}
}

/* a phone: 20px margins */
@media (max-width: 640px) {
  :root { --margin-page: 20px; }
}
`,
);
console.log(`public/tokens.css: ${light.length} tokens, ${dark.length} with dark values`);
